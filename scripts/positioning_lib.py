"""Views over content/positioning.json: one record, every consumer (docs/adr/0002).

The record is the only copy of the 三大模型 · 三大基础 text. Slides reference it with
`{"$positioning": "<view>"}` and the website section is generated by
`scripts/build_positioning.py`; neither may carry its own wording.
"""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]
SCHEMA = 'tiansight.positioning/1'
SCENARIO_ROWS = (('question', '要回答的问题'), ('inputs', '输入'), ('output', '产出'), ('cadence', '节奏'), ('acceptance', '验收'))


def load(root=ROOT):
    record = json.loads((Path(root) / 'content/positioning.json').read_text())
    validate(record)
    return record


def validate(record):
    if record.get('schema') != SCHEMA:
        raise ValueError('positioning: unknown schema')
    if record.get('status') not in ('draft', 'approved'):
        raise ValueError('positioning: status must be draft or approved')
    if record['status'] == 'approved' and not record.get('approval'):
        raise ValueError('positioning: approved records carry an approval')
    models = record['models']
    if [m['id'] for m in models] != ['operating', 'profit', 'talent']:
        raise ValueError('positioning: models must be operating, profit, talent in that order')
    for model in models:
        for key in ('eyebrow', 'title', 'note', 'body'):
            if not record['lead'].get(key):
                raise ValueError(f'positioning: lead lacks {key}')
        for key in ('numeral', 'name', 'en', 'tagline', 'aim', 'headline'):
            if not model.get(key):
                raise ValueError(f'positioning: model {model["id"]} lacks {key}')
    operating, profit, talent = models
    if len(operating['scenarios']) != 3 or [s['verb'] for s in operating['scenarios']] != operating['verbs']:
        raise ValueError('positioning: operating verbs and scenarios must match one to one')
    for scenario in operating['scenarios']:
        if scenario['module'] not in record['refs']['modules'] or scenario['stage'] not in record['refs']['stages']:
            raise ValueError(f'positioning: scenario {scenario["id"]} references an unknown module or stage')
        for key, _ in SCENARIO_ROWS:
            if not scenario.get(key):
                raise ValueError(f'positioning: scenario {scenario["id"]} lacks {key}')
    if len(profit['dimensions']) != 4 or len(talent['roles']) != 6 or len(talent['dimensions']) != 4:
        raise ValueError('positioning: profit has four dimensions, talent six roles and four dimensions')
    foundations = record['foundations']['items']
    if [f['id'] for f in foundations] != ['knowledge-base', 'decision-tree', 'capability-table']:
        raise ValueError('positioning: three foundations in the documented order')
    ids = {m['id'] for m in models}
    for item in foundations:
        if set(item['supports']) - ids or not item['supports']:
            raise ValueError(f'positioning: foundation {item["id"]} supports unknown models')
        if item.get('state') not in ('在用', '编制中'):
            raise ValueError(f'positioning: foundation {item["id"]} state')


def model(record, mid):
    return next(m for m in record['models'] if m['id'] == mid)


def view(record, name):
    """Component props for one slide view. Copy comes only from the record."""
    lead, foundations = record['lead'], record['foundations']
    if name == 'models:steps':
        return {'eyebrow': lead['eyebrow'], 'title': lead['title'], 'note': lead['note'],
                'steps': [{'label': m['name'], 'q': m['tagline'], 'aim': m['aim']} for m in record['models']]}
    if name == 'operating:matrix':
        m = model(record, 'operating')
        scenarios = m['scenarios']
        modules = record['refs']['modules']
        return {'eyebrow': f"{m['name']} · {m['en']}", 'title': m['headline'], 'subtitle': '',
                'corner': ' · '.join(m['verbs']),
                'columns': [f"{s['verb']} · {s['name']}" for s in scenarios],
                'rows': [{'label': label, 'cells': [s[key] for s in scenarios]} for key, label in SCENARIO_ROWS],
                'footnote': {'label': '对应服务模块', 'text': ' · '.join(f"{s['name']} → {modules[s['module']]}" for s in scenarios)}}
    if name == 'profit:tiers':
        m = model(record, 'profit')
        return {'eyebrow': f"{m['name']} · {m['en']}", 'title': m['headline'], 'gotLabel': '做什么',
                'tiers': [{'tier': d['en'], 'name': d['name'], 'got': d['body']} for d in m['dimensions']]}
    if name == 'profit:shift':
        m = model(record, 'profit')
        s = m['shift']
        return {'eyebrow': f"{m['name']} · 节奏升级", 'title': '由每月算一次，升级为每天复盘。', 'subtitle': m['objective'],
                'corner': '复盘节奏', 'columns': ['现在', '升级后'],
                'rows': [{'label': '算账', 'cells': [s['from'], s['to']]},
                         {'label': '分工', 'cells': ['月底由财务汇总', s['by']]},
                         {'label': '结果', 'cells': ['问题下个月才看见', m['effect']]}],
                'footnote': None}
    if name == 'talent:roles':
        m = model(record, 'talent')
        return {'eyebrow': f"{m['name']} · {m['en']}", 'title': m['tagline'], 'subtitle': m['shift']['by'], 'columns': 3, 'numbered': True,
                'items': [{'tag': r['holds'], 'title': r['name'], 'body': r['needs']} for r in m['roles']]}
    if name == 'talent:tiers':
        m = model(record, 'talent')
        s = m['shift']
        return {'eyebrow': f"{m['name']} · {s['from']} → {s['to']}", 'title': m['headline'], 'gotLabel': '做法',
                'tiers': [{'tier': d['en'], 'name': d['name'], 'got': d['body']} for d in m['dimensions']]}
    if name == 'foundations:cards':
        return {'eyebrow': foundations['eyebrow'], 'title': foundations['title'], 'subtitle': foundations['body'], 'columns': 3, 'numbered': True,
                'items': [{'tag': f"{f['en']} · {f['state']}", 'title': f['name'], 'body': f['body']} for f in foundations['items']]}
    raise ValueError(f'Unknown positioning view: {name}')


VIEWS = ('models:steps', 'operating:matrix', 'profit:tiers', 'profit:shift', 'talent:roles', 'talent:tiers', 'foundations:cards')


if __name__ == '__main__':
    record = load()
    for name in VIEWS:
        view(record, name)
    print(f"positioning {record['version']} ({record['status']}): {len(VIEWS)} views valid")
