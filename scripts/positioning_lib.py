"""Views over content/positioning.json: one record, every consumer (docs/adr/0002).

The record holds the 1 + 3 + 3 structure: one ecosystem base, three models with their
outcomes, three foundations. It stores names and short labels only, never explanatory
sentences. Slides reference it with `{"$positioning": "<view>"}` and the website section is
generated by `scripts/build_positioning.py`; neither may carry its own wording.
"""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]
SCHEMA = 'tiansight.positioning/2'
MODEL_IDS = ['operating', 'profit', 'capability']
FOUNDATION_IDS = ['knowledge-base', 'decision-tree', 'capability-table']
MAX_LABEL = 16  # labels, not sentences


def load(root=ROOT):
    record = json.loads((Path(root) / 'content/positioning.json').read_text())
    validate(record)
    return record


def _label(value, where):
    if not isinstance(value, str) or not value.strip():
        raise ValueError(f'positioning: {where} must be a label')
    if len(value) > MAX_LABEL or any(mark in value for mark in '。；！？'):
        raise ValueError(f'positioning: {where} is a sentence, not a label: {value}')


def validate(record):
    if record.get('schema') != SCHEMA:
        raise ValueError('positioning: unknown schema')
    if record.get('status') not in ('draft', 'approved'):
        raise ValueError('positioning: status must be draft or approved')
    if record['status'] == 'approved' and not record.get('approval'):
        raise ValueError('positioning: approved records carry an approval')
    lead, base = record['lead'], record['base']
    if lead.get('formula') != '1 + 3 + 3' or not lead.get('title'):
        raise ValueError('positioning: lead needs the 1 + 3 + 3 formula and a title')
    _label(base['name'], 'base.name')
    if base.get('numeral') != '1' or not base.get('members'):
        raise ValueError('positioning: one base with its members')
    for member in base['members']:
        _label(member, 'base.members')
    models = record['models']
    if [m['id'] for m in models] != MODEL_IDS:
        raise ValueError('positioning: models must be operating, profit, capability in that order')
    for m in models:
        for key in ('numeral', 'name', 'en', 'outcome'):
            _label(m.get(key), f'{m["id"]}.{key}')
        if not m.get('keys'):
            raise ValueError(f'positioning: {m["id"]} needs its keys')
        for key in m['keys']:
            _label(key, f'{m["id"]}.keys')
    operating, profit, capability = models
    if [s['verb'] for s in operating['scenarios']] != operating['keys'] or len(operating['scenarios']) != 3:
        raise ValueError('positioning: operating keys and scenarios match one to one')
    for s in operating['scenarios']:
        _label(s['name'], 'operating.scenarios')
    if len(profit['sources']) != 2 or len(profit['flow']) != 4 or not profit['flow'][-1].get('loss'):
        raise ValueError('positioning: profit has two sources and four flow steps ending in a loss')
    for item in profit['flow']:
        _label(item['name'], 'profit.flow')
    if len(capability['roles']) != 6 or sum(1 for r in capability['roles'] if r.get('agent')) != 1:
        raise ValueError('positioning: capability has six roles, one of them the AI agent')
    if len(capability['keys']) != 3 or not capability.get('focus'):
        raise ValueError('positioning: capability has three keys and a focus')
    foundations = record['foundations']
    if [f['id'] for f in foundations] != FOUNDATION_IDS:
        raise ValueError('positioning: three foundations in the documented order')
    if [f['under'] for f in foundations] != MODEL_IDS:
        raise ValueError('positioning: each foundation sits under one model, in model order')
    for f in foundations:
        _label(f['name'], 'foundations.name')
        _label(f['full'], 'foundations.full')


def model(record, mid):
    return next(m for m in record['models'] if m['id'] == mid)


def base_line(record):
    base = record['base']
    return f"{' + '.join(base['members'])} · {base['name']}"


def does(m):
    if m['id'] == 'profit':
        return ' → '.join(item['name'] for item in m['flow'])
    return ' · '.join(m['keys'])


def view(record, name):
    """Component props for one slide view. Copy comes only from the record."""
    lead, foundations = record['lead'], record['foundations']
    if name == 'system:matrix':
        models = record['models']
        under = {f['under']: f for f in foundations}
        return {'eyebrow': lead['formula'], 'title': lead['title'], 'subtitle': '', 'corner': lead['formula'],
                'columns': [m['name'] for m in models],
                'rows': [{'label': '结果', 'cells': [m['outcome'] for m in models]},
                         {'label': '做什么', 'cells': [does(m) for m in models]},
                         {'label': '底座', 'cells': [under[m['id']]['name'] for m in models]}],
                'footnote': {'label': f"{record['base']['numeral']} · 基座", 'text': base_line(record)}}
    if name == 'operating:steps':
        m = model(record, 'operating')
        return {'eyebrow': f"{m['numeral']} · {m['name']} · {m['en']}", 'title': f"{m['outcome']}。", 'note': '',
                'steps': [{'label': s['verb'], 'q': s['name'], 'aim': ''} for s in m['scenarios']]}
    if name == 'profit:steps':
        m = model(record, 'profit')
        r = m['rhythm']
        return {'eyebrow': f"{m['numeral']} · {m['name']} · {m['en']}", 'title': f"{m['outcome']}。",
                'note': f"{' × '.join(m['sources'])} · {r['from']} → {r['to']}",
                'steps': [{'label': item['name'], 'q': '', 'aim': ''} for item in m['flow']]}
    if name == 'capability:steps':
        m = model(record, 'capability')
        s = m['shift']
        return {'eyebrow': f"{m['numeral']} · {m['name']} · {m['en']}", 'title': f"{m['outcome']}。",
                'note': f"{' · '.join(m['focus'])} ｜ {' · '.join(r['name'] for r in m['roles'])} ｜ {s['from']} → {s['to']}",
                'steps': [{'label': key, 'q': '', 'aim': ''} for key in m['keys']]}
    if name == 'foundations:cards':
        names = {m['id']: m['name'] for m in record['models']}
        return {'eyebrow': f"3 · 底座 ＋ {record['base']['numeral']} · 基座", 'title': ' · '.join(f['name'] for f in foundations),
                'subtitle': base_line(record), 'columns': 3, 'numbered': True,
                'items': [{'tag': names[f['under']], 'title': f['full'], 'body': f['en']} for f in foundations]}
    raise ValueError(f'Unknown positioning view: {name}')


VIEWS = ('system:matrix', 'operating:steps', 'profit:steps', 'capability:steps', 'foundations:cards')


if __name__ == '__main__':
    record = load()
    for name in VIEWS:
        view(record, name)
    print(f"positioning {record['version']} ({record['status']}): {len(VIEWS)} views valid")
